// 1. Introduction to Git and GitHub
// Git is a version control system used to track source code changes. GitHub is a cloud platform used to store repositories and collaborate with teams.
// Git helps maintain project history.
// GitHub helps developers collaborate together.
// Feature branches are used for development.
// Pull Requests are used for code review.
// 2. Install Git
// Git must be installed before starting project version control.
// Download Git from: https://git-scm.com/downloads
// Install Git using default settings.
// Verify installation using command below.
// 3. Verify Git Installation
// Open Command Prompt and execute commands.
// git --version
// git config --global user.name "Your Name"//PTtest
// git config --global user.email "yourmail@gmail.com"//piyushthakur64@gmail.com
// 4. Create GitHub Repository
// Repository is used to store project code in GitHub cloud.
// Login to GitHub
// Click New Repository
// Enter repository name
// Select Public
// Click Create Repository
// 5. Create Local Project
// Create local automation project in your machine.
// 6. Initialize Git Repository
// Initialize local Git repository.
// git init
// git status
// 7. First Commit Flow
// Commit initial project code into local repository.
// git add .
// git commit -m "Initial project setup"
// 8. Connect Local Project with GitHub
// Link local repository with remote GitHub repository.
// git remote add origin https://github.com/username/playwright-project.git
// git branch -M main
// git push -u origin main